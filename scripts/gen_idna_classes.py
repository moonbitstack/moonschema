"""Write `src/idna_classes.mbt` from the derived property tables of RFC 5892.

`hostname` and `idn-hostname` are one question: is every code point of every
label one that IDNA2008 permits, and do the contextual ones sit where the
standard says they may. RFC 5892 §2 derives that property from the Unicode
character database, and the derivation is not something to redo at startup: it
is a table, so it is generated here and read from the source.

The tables come from the `idna` package's `idnadata`, which carries the derived
property for Unicode 15.1 as published, read through the same range test the
package itself uses. Run it with the interpreter that has `idna` installed:

    python scripts/gen_idna_classes.py

The output is checked in, so a build never needs Python.
"""
import pathlib
import sys
import unicodedata

try:
    import idna.idnadata as data
    from idna.intranges import intranges_contain
except ImportError:  # pragma: no cover - the message is the point
    sys.exit("gen_idna_classes.py needs the `idna` package: pip install idna")

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "idna_classes.mbt"


def ranges_of(points):
    """A sorted set of code points as merged inclusive ranges."""
    out = []
    for cp in sorted(points):
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [(low, high) for low, high in out]


def of_classes(*names):
    points = []
    for cp in range(0x110000):
        for name in names:
            if intranges_contain(cp, data.codepoint_classes[name]):
                points.append(cp)
                break
    return ranges_of(points)


def of_categories(names):
    return ranges_of(
        [cp for cp in range(0x110000) if unicodedata.category(chr(cp)) in names]
    )


def of_combining_class(wanted):
    return ranges_of(
        [cp for cp in range(0x110000) if unicodedata.combining(chr(cp)) == wanted]
    )


def of_joining(letters):
    """Every code point whose joining type is one of `letters`.

    The published table holds the type as the character it is named by, so the
    letters are turned into their codes here rather than at a call site.
    """
    codes = {ord(letter) for letter in letters}
    return ranges_of(
        [cp for cp, kind in data.joining_types.items() if kind in codes]
    )


def literal(name, ranges, note):
    flat = []
    for low, high in ranges:
        flat.append(f"0x{low:X}, 0x{high:X}")
    body = []
    for i in range(0, len(flat), 6):
        body.append("  " + ", ".join(flat[i : i + 6]) + ",")
    return f'///|\n/// {note}\nlet {name} : Array[Int32] = [\n' + "\n".join(body) + "\n]\n"


def main():
    head = f"""// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by `scripts/gen_idna_classes.py` from the derived property tables
// of RFC 5892, as the `idna` package publishes them for Unicode {
        data.__version__
    }. Do not edit: run the script.

"""
    parts = [
        head,
        literal(
            "idna_allowed",
            of_classes("PVALID", "CONTEXTJ", "CONTEXTO"),
            "PVALID, CONTEXTJ and CONTEXTO: the code points a label may hold, "
            "every other one being DISALLOWED.",
        ),
        literal(
            "idna_contextj",
            of_classes("CONTEXTJ"),
            "The join controls, which may only sit where RFC 5892 Appendix A "
            "says they may.",
        ),
        literal(
            "idna_marks",
            of_categories({"Mn", "Mc", "Me"}),
            "Combining marks, which a label may not begin with.",
        ),
        literal(
            "idna_virama",
            of_combining_class(9),
            "Canonical combining class 9, which a join control may follow.",
        ),
        literal(
            "idna_join_left",
            of_joining({"L", "D"}),
            "Joining types L and D: what may stand before a zero width "
            "non-joiner.",
        ),
        literal(
            "idna_join_transparent",
            of_joining({"T"}),
            "Joining type T, which a zero width non-joiner may skip over.",
        ),
        literal(
            "idna_join_right",
            of_joining({"R", "D"}),
            "Joining types R and D: what may stand after a zero width "
            "non-joiner.",
        ),
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)} written")


if __name__ == "__main__":
    main()
